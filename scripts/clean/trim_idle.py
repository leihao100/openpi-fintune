"""
trim_idle_lerobot.py — Trim idle frames from a LeRobot v2.1 dataset using
the official LeRobot 0.3.x API, with batch-decode + GPU-encode acceleration.
 
Speedups vs naive lerobot-only path:
  - Batch decode each episode video once (avoids per-frame seek, ~10x faster).
  - PTS-ordered frame list (correctness against B-frame reorder).
  - GPU h264_nvenc when available, falls back to CPU h264, then libsvtav1.
  - Bulk pandas column access instead of df.iloc[i][k] (5-10x faster).
  - Pre-stack vector columns once per episode.
 
Correctness preserved:
  - Per-episode normalization stats recomputed by lerobot's save_episode().
  - meta/info.json, episodes.jsonl, tasks.jsonl auto-managed.
  - frame_index / timestamp / index regenerated by lerobot.
  - chunk path computed from chunks_size (works for >=1000 episodes).
  - Frame-vs-parquet length asserted before any writes.
 
Tested target:
  - lerobot == 0.3.3
  - dataset codebase_version == "v2.1"
 
Gripper convention assumed:
  action 0 -> 1  =  OPEN
  action 1 -> 0  =  CLOSE

Multi-arm / multi-camera:
  - Video keys are auto-detected from features (dtype == "video"), so any
    number of cameras (e.g. 3) is handled with no code changes.
  - Idle detection treats EVERY non-gripper action dim as a motion dim and
    every gripper (configurable list of indices) independently. A frame is
    idle only if the arm is not being commanded to move AND all grippers are
    static. Gripper events / close-protection take the union across grippers.
  - The arm-motion signal depends on what `action` means (--motion-idle-mode):
        target : action is an ABSOLUTE target position (controller setpoint);
                 idle when the target is unchanged frame-to-frame.   [default]
        delta  : action dims are deltas/velocities; idle when ~0.
  - Default dual-arm UR3 action layout (16-dim):
        [0..6]  left  arm eef
        [7..13] right arm eef
        [14]    left  gripper
        [15]    right gripper
    observation.state uses the SAME 16-dim layout, so the gripper indices
    match: --gripper-act-idx 14,15 and --gripper-obs-idx 14,15 (both default).
"""
 
