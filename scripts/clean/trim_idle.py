def _parse_idx_list(s):
    """Parse a comma-separated index list, e.g. '14,15' -> [14, 15]."""
    if isinstance(s, (list, tuple)):
        return [int(x) for x in s]
    return [int(x) for x in str(s).split(",") if str(x).strip() != ""]
 
 
